#!/usr/bin/env python3
"""
Write a copy of a paper .tex whose \\includegraphics / \\input paths point to the
standardized files in flat folders next to it (graphs/Figure-1-a, tables/Table-D3, ...), and whose
pasted tables import only their BODY from the replication package.

Usage:
    python rewrite_tex_paths.py --rename-map rename_map.json SOURCE.tex \
        --out <target>/1-paper/<ID>-main-<DATE>.tex [--bodies-dir <target>/_migration/original_bodies]

Never edits SOURCE.tex.

Tables — "numbers from code, presentation from the paper":
  For every table whose body was pasted into the .tex (status "inline" with body_lines), the
  rows between the header rule (\\midrule) and \\bottomrule are replaced by
      \\input{./tables/Table-N}
  The head (caption, label, column headers) and foot (\\bottomrule, notes) stay exactly as in the
  final paper. The removed rows are saved to --bodies-dir/Table-N.tex: they are the reference
  that compare_tables.py checks the regenerated body against.
  Tables \\input / \\include'd as COMPLETE files (their own tabular head/foot, often edited by hand
  so they "look right"): the file's content is inlined into the paper — head and foot verbatim —
  and its body rows are replaced by \\input{./tables/Table-N}; the original body is saved the
  same way. Disable with --keep-table-files.
  Tables matched to two files (panels) and tables inside \\input'ed section files are listed for
  manual treatment: keep panel header rows in the .tex and \\input Table-N-Panel-A / -B bodies.

Also removes \\graphicspath and lists references it did not recognise.

To split a single paper+appendix .tex into the two template documents, run this once per
output and then cut the body at \\appendix (keep the preamble in both; add \\appendix plus
\\counterwithin{figure}{section} and \\counterwithin{table}{section} at the top of the appendix body).
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _safety import assert_writable, read_text_retry, probe  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from parse_latex import blank_comments, table_body_span  # noqa: E402

RX = re.compile(r"(\\(?:includegraphics\s*(?:\[[^\]]*\])?|input|include)\s*\{)([^}]+)(\})")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rename-map", type=Path, required=True)
    ap.add_argument("tex", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--bodies-dir", type=Path, default=None,
                    help="where to save the pasted table bodies (default: <out>/../../_migration/original_bodies)")
    ap.add_argument("--keep-inline", action="store_true", help="do not replace pasted table bodies")
    ap.add_argument("--keep-table-files", action="store_true",
                    help="keep \\input of complete table files instead of moving their head/foot into the paper")
    a = ap.parse_args()
    if a.out.resolve() == a.tex.resolve():
        raise SystemExit("refusing to overwrite the source .tex — choose a different --out")
    rm = json.loads(a.rename_map.read_text())
    root = Path(rm.get("project_root", "."))
    src_rel = os.path.relpath(a.tex.resolve(), root)
    bodies = a.bodies_dir or a.out.resolve().parent.parent / "_migration" / "original_bodies"

    mapping = {e["latex_path"].strip(): e["latex_new_path"] for e in rm["entries"] if e.get("latex_path")}
    assert_writable(a.out, [root])
    assert_writable(bodies, [root])
    text = read_text_retry(a.tex).replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")

    # 1. pasted table bodies -> \input of the generated body (bottom-up so line numbers stay valid)
    manual, replaced = [], 0
    inline = [e for e in rm["entries"] if e["status"] == "inline"]
    for e in sorted(inline, key=lambda x: -(x.get("body_lines") or [0])[0]):
        if a.keep_inline:
            break
        if e.get("origin") != src_rel:
            if e.get("doc") == src_rel:
                manual.append(e)          # pasted inside an \input'ed section file
            continue
        if e.get("matched_panels") or not e.get("body_lines"):
            manual.append(e)
            continue
        l1, l2 = e["body_lines"]
        body = "\n".join(lines[l1 - 1:l2])
        bodies.mkdir(parents=True, exist_ok=True)
        (bodies / f"{e['name']}.tex").write_text(body + "\n", encoding="utf-8")
        new = f"tables/{e['name']}"  # flat tables/ folder next to the .tex
        lines[l1 - 1:l2] = [f"\\input{{./{new}}}  % body generated by the replication package; original rows in _migration/original_bodies/{e['name']}.tex"]
        replaced += 1

    # 2. complete table files (\input / \include of a .tex that has its own tabular head/foot, often
    #    hand-edited): inline the file here, keeping its head/foot verbatim, and \input only the body
    full = {e["latex_path"].strip(): e for e in rm["entries"]
            if e.get("table_file") == "full" and e["status"] == "ok" and e.get("latex_path")}
    moved = 0
    rx_inc = re.compile(r"\\(?:input|include)\s*\{([^}]+)\}")
    for i, ln in enumerate(lines):
        if a.keep_table_files:
            break
        c = re.search(r"(?<!\\)%", ln)
        code, comment = (ln[:c.start()], ln[c.start():]) if c else (ln, "")
        m = rx_inc.search(code)
        if not m or m.group(1).strip() not in full:
            continue
        e = full[m.group(1).strip()]
        raw = read_text_retry(root / e["sources"][0]).replace("\r\n", "\n")
        span = table_body_span(blank_comments(raw))
        if not span:
            manual.append(e)
            continue
        b0, b1 = span
        bodies.mkdir(parents=True, exist_ok=True)
        (bodies / f"{e['name']}.tex").write_text(raw[b0:b1].rstrip("\n") + "\n", encoding="utf-8")
        inl = (f"% --- {e['name']}: head/foot moved here from {e['sources'][0]}; body generated by the replication package ---\n"
               + raw[:b0] + f"\\input{{./tables/{e['name']}}}\n" + raw[b1:].rstrip("\n")
               + f"\n% --- end {e['name']} ---")
        lines[i] = code[:m.start()] + inl + code[m.end():] + comment
        moved += 1

    # 3. graphics / \input paths
    changed, unknown = 0, []

    def sub(m):
        nonlocal changed
        arg = m.group(2).strip()
        if arg in mapping:
            changed += 1
            return m.group(1) + "./" + mapping[arg] + m.group(3)
        if "includegraphics" in m.group(1) or (re.search(r"tab|fig|graph", arg, re.I) and not arg.startswith("./tables/")):
            unknown.append(arg)
        return m.group(0)

    for i, ln in enumerate(lines):
        c = re.search(r"(?<!\\)%", ln)
        code, comment = (ln[:c.start()], ln[c.start():]) if c else (ln, "")
        lines[i] = RX.sub(sub, code) + comment
    out = "\n".join(lines)
    out = re.sub(r"^(\s*\\graphicspath)", r"% removed for replication package: \1", out, flags=re.M)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(out, encoding="utf-8")
    print(f"✅ {a.out}: {changed} path(s) rewritten, {replaced} pasted table bod(y/ies) replaced by \\input, "
          f"{moved} complete table file(s) split (head/foot moved into the paper)"
          + (f" (originals saved in {bodies})" if replaced else ""))
    if manual:
        print(f"⚠️  {len(manual)} pasted table(s) need manual treatment:")
        for e in manual:
            why = "complete table file without \\midrule/\\bottomrule — split head/body/foot by hand" if e.get("table_file") == "full" \
                else "panels: keep panel header rows, \\input each Table-N-Panel-X body" if e.get("matched_panels") \
                else "inside an \\input'ed section file — edit that file" if e.get("origin") != src_rel \
                else "no \\midrule/\\bottomrule body found — split head/body/foot by hand"
            print(f"   {e['name']} at {e['origin']}:{e['line']} {e.get('label', '')} — {why}")
    if unknown:
        print(f"⚠️  {len(unknown)} reference(s) not in the rename map (left unchanged):")
        for u in sorted(set(unknown))[:30]:
            print("   ", u)


if __name__ == "__main__":
    main()
